CREATE OR REPLACE FUNCTION public.add_member(p_member_name text)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_uid uuid := auth.uid();
  v_group_id uuid;
  v_member_id uuid;
  v_count int;
begin
  select m.group_id into v_group_id
  from public.members m
  where m.user_id = v_uid and m.is_owner = true;

  if v_group_id is null then
    raise exception 'Only the group owner can add people.';
  end if;

  if trim(coalesce(p_member_name,'')) = '' or char_length(trim(p_member_name)) > 40 then
    raise exception 'Name must be 1–40 characters.';
  end if;

  select count(*) into v_count from public.members where group_id = v_group_id;
  if v_count >= 50 then
    raise exception 'This app supports up to 50 people per group.';
  end if;

  if exists (
    select 1 from public.members
    where group_id = v_group_id and lower(name) = lower(trim(p_member_name))
  ) then
    raise exception 'That name is already in the group.';
  end if;

  insert into public.members(group_id, name)
  values (v_group_id, trim(p_member_name))
  returning id into v_member_id;

  return v_member_id;
end;
$function$;
