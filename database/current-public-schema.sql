CREATE OR REPLACE FUNCTION public.save_availability(p_day date, p_type text, p_note text DEFAULT NULL::text, p_repeat_weeks integer DEFAULT 1)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_member_id uuid := public.current_member_id();
  v_group_id uuid := public.current_group_id();
  v_role text;
  v_type text := lower(trim(coalesce(p_type, '')));
  v_note text := nullif(trim(coalesce(p_note, '')), '');
  i integer;
  v_target date;
begin
  select m.role into v_role
  from public.members m
  where m.id = v_member_id;

  if v_member_id is null or v_group_id is null then
    raise exception 'You are not linked to a group.';
  end if;

  if v_role <> 'member' then
    raise exception 'Viewers cannot change availability.';
  end if;

  if v_type not in ('off', 'partial') then
    raise exception 'Availability type must be off or partial.';
  end if;

  if p_day is null then
    raise exception 'Choose a date.';
  end if;

  if p_repeat_weeks < 1 or p_repeat_weeks > 12 then
    raise exception 'Repeat must be between 1 and 12 weeks.';
  end if;

  if v_note is not null and char_length(v_note) > 200 then
    raise exception 'Note must be 200 characters or fewer.';
  end if;

  for i in 0..(p_repeat_weeks - 1) loop
    v_target := p_day + (i * 7);

    insert into public.days_off(
      group_id, member_id, day, availability_type, note,
      source, import_file_name, imported_at
    )
    values (
      v_group_id, v_member_id, v_target, v_type, v_note,
      'manual', null, null
    )
    on conflict (member_id, day)
    do update set
      availability_type = excluded.availability_type,
      note = excluded.note,
      source = 'manual',
      import_file_name = null,
      imported_at = null;
  end loop;
end;
