CREATE OR REPLACE FUNCTION public.join_group(p_invite_code text, p_member_name text)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_uid uuid := auth.uid();
  v_group_id uuid;
  v_member_id uuid;
begin
  if v_uid is null then
    raise exception 'You must be signed in.';
  end if;

  if exists(select 1 from public.member_devices where user_id = v_uid) then
    raise exception 'This browser is already linked to a person.';
  end if;

  select g.id into v_group_id
  from public.groups g
  where g.invite_code = upper(
    regexp_replace(coalesce(p_invite_code,''), '[^A-Za-z0-9]', '', 'g')
  );

  if v_group_id is null then
    raise exception 'Group code not found.';
  end if;

  select m.id into v_member_id
  from public.members m
  where m.group_id = v_group_id
    and lower(m.name) = lower(trim(p_member_name))
    and not exists (
      select 1 from public.member_devices d where d.member_id = m.id
    )
  for update;

  if v_member_id is null then
    raise exception 'That name is already linked, or was not found.';
  end if;

  insert into public.member_devices(member_id, user_id)
  values (v_member_id, v_uid);

  -- Keep the original column populated for backwards compatibility.
  update public.members
  set user_id = coalesce(user_id, v_uid)
  where id = v_member_id;

  return v_group_id;
end;
